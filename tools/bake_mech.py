"""US-T83: bake the walking mech's parts into C++ (Cpp/Source/SpaceGod/Rendering/MechMeshData.inl).

  python tools/bake_mech.py

Reads Cpp/SourceArt/Mech/SM_Mech_<Part>.obj and Mech_Texture.png: Quaternius's CC0 "George" mech (Animated Mech Pack,
March 2021), split into 13 rigid parts with gun arms and missile pods by Unreal.Soulslike's tools/convert_mech.py
(UNR-T68) and copied here (docs/ThirdPartyArt.md). The game draws through its Unity-shaped layer with vertex-coloured
procedural materials and no imported assets, so each part is written out as plain arrays the Runtime builds a Mesh from
(Rendering/MechModel): every corner's position (part frame, pivot at the joint, tenths of a centimetre), its normal and a
palette colour sampled from the texture at the corner's UV (snapped to steps of 8 a channel, so the corners of a face
(and of its neighbours) on the same texel share it).

Axes. convert_mech.py writes a point (x, y, z) of Unreal space (cm, +X forward, +Y right, +Z up) as (x, -y, z). The game's
mech frame is Unity's (+X right, +Y up, +Z forward), so an OBJ point (ox, oy, oz) is (-oy, oz, ox) there: a mirror, as the
right-handed OBJ becomes left-handed, so the OBJ's anticlockwise faces are already the game's clockwise front faces.
"""
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "Cpp", "SourceArt", "Mech")
OUT = os.path.join(ROOT, "Cpp", "Source", "SpaceGod", "Rendering", "MechMeshData.inl")

PARTS = ["Pelvis", "Torso", "Canopy", "ArmL", "ArmR", "ThighL", "ShinL", "MetaL", "FootL", "ThighR", "ShinR", "MetaR", "FootR"]


def read_obj(path):
    vs, vts, vns, faces = [], [], [], []
    with open(path, encoding="utf-8") as f:
        for line in f:
            p = line.split()
            if not p:
                continue
            if p[0] == "v":
                vs.append(tuple(float(c) for c in p[1:4]))
            elif p[0] == "vt":
                vts.append(tuple(float(c) for c in p[1:3]))
            elif p[0] == "vn":
                vns.append(tuple(float(c) for c in p[1:4]))
            elif p[0] == "f":
                corners = []
                for c in p[1:]:
                    i = c.split("/")
                    corners.append((int(i[0]) - 1, int(i[1]) - 1 if len(i) > 1 and i[1] else -1, int(i[2]) - 1 if len(i) > 2 and i[2] else -1))
                for k in range(1, len(corners) - 1):
                    faces.append((corners[0], corners[k], corners[k + 1]))
    return vs, vts, vns, faces


def main():
    tex = Image.open(os.path.join(SRC, "Mech_Texture.png")).convert("RGB")
    w, h = tex.size
    palette, palette_index = [], {}

    def colour_at(u, v):
        x = min(w - 1, max(0, int((u - int(u) if u >= 0 else u % 1) * w)))
        y = min(h - 1, max(0, int((1 - (v - int(v) if v >= 0 else v % 1)) * h)))
        r, g, b = tex.getpixel((x, y))
        # Snap each channel to steps of 8 so near-identical texels share a palette entry.
        key = (r // 8 * 8, g // 8 * 8, b // 8 * 8)
        if key not in palette_index:
            palette_index[key] = len(palette)
            palette.append(key)
        return palette_index[key]

    out = []
    out.append("// GENERATED by tools/bake_mech.py from Cpp/SourceArt/Mech (Quaternius, CC0 1.0): do not edit by hand.")
    out.append("// US-T83: the walking mech's 13 rigid parts. Positions in tenths of a centimetre in the part's frame (Unity axes,")
    out.append("// +X right, +Y up, +Z forward; pivot at the joint), normals scaled to 127, colours an index into MechPalette.")
    out.append("")
    parts_out = []
    total_v = total_t = 0
    for name in PARTS:
        vs, vts, vns, faces = read_obj(os.path.join(SRC, "SM_Mech_%s.obj" % name))
        verts, index, tris = [], {}, []
        for face in faces:
            for c in face:
                u, v = vts[c[1]] if c[1] >= 0 else (0.0, 0.0)
                col = colour_at(u, v)
                ox, oy, oz = vs[c[0]]
                nx, ny, nz = vns[c[2]] if c[2] >= 0 else (0.0, 1.0, 0.0)
                p = (int(round(-oy * 10)), int(round(oz * 10)), int(round(ox * 10)))
                n = (int(round(-ny * 127)), int(round(nz * 127)), int(round(nx * 127)))
                key = (p, n, col)
                if key not in index:
                    index[key] = len(verts)
                    verts.append(key)
                tris.append(index[key])
        for (p, _, _) in verts:
            for c in p:
                if not -32768 <= c <= 32767:
                    sys.exit("%s: a coordinate does not fit 16 bits" % name)
        total_v += len(verts)
        total_t += len(tris) // 3
        vlines = []
        row = []
        for (p, n, col) in verts:
            row.append("{%d,%d,%d,%d,%d,%d,%d}" % (p[0], p[1], p[2], n[0], n[1], n[2], col))
            if len(row) == 8:
                vlines.append("\t" + ",".join(row) + ",")
                row = []
        if row:
            vlines.append("\t" + ",".join(row) + ",")
        ilines = []
        for k in range(0, len(tris), 30):
            ilines.append("\t" + ",".join(str(i) for i in tris[k:k + 30]) + ",")
        out.append("static const MechVertex Mech%sVertices[] = {" % name)
        out.extend(vlines)
        out.append("};")
        out.append("static const uint16_t Mech%sIndices[] = {" % name)
        out.extend(ilines)
        out.append("};")
        out.append("")
        if len(verts) > 65535:
            sys.exit("%s: too many vertices for 16-bit indices" % name)
        parts_out.append(name)
        print("MECH %-7s %5d vertices %5d triangles" % (name, len(verts), len(tris) // 3))
    out.append("static const MechColour MechPalette[] = {")
    out.append("\t" + ",".join("{%d,%d,%d}" % c for c in palette) + ",")
    out.append("};")
    out.append("")
    out.append("static const MechPartData MechParts[%d] = {" % len(parts_out))
    for name in parts_out:
        out.append("\t{ \"%s\", Mech%sVertices, static_cast<int>(sizeof(Mech%sVertices) / sizeof(MechVertex)), Mech%sIndices, "
                   "static_cast<int>(sizeof(Mech%sIndices) / sizeof(uint16_t)) }," % (name, name, name, name, name))
    out.append("};")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("MECH total %d vertices %d triangles, %d palette colours -> %s" % (total_v, total_t, len(palette), OUT))


if __name__ == "__main__":
    main()
